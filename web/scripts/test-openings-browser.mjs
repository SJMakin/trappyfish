import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

const appUrl = process.env.TRAPPY_TEST_URL ?? 'http://127.0.0.1:5173';
const channel = process.env.TRAPPY_BROWSER_CHANNEL ?? (process.platform === 'win32' ? 'msedge' : undefined);
const browser = await chromium.launch({ ...(channel ? { channel } : {}), headless: true });
await mkdir('artifacts/openings', { recursive: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 320, height: 800 }, reducedMotion: 'reduce' });
  page.on('pageerror', (error) => errors.push(error.message));
  let requests = 0;
  await page.route('https://explorer.lichess.*/**', async (route) => {
    requests++;
    const url = new URL(route.request().url());
    assert.equal(url.searchParams.get('speeds'), 'rapid');
    if (requests === 1) {
      assert.equal(url.searchParams.get('ratings'), '1000,1200,1400,1600');
      await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ white: 4, draws: 2, black: 4, moves: [{ uci: 'f1b5', san: 'Bb5', white: 4, draws: 2, black: 4 }] }) });
    } else await route.fulfill({ status: 429, headers: { 'Retry-After': '120' }, body: '' });
  });
  await page.goto(`${appUrl}/?mode=play`);
  await page.getByRole('button', { name: 'Explore openings', exact: true }).click();
  const library = page.locator('.opening-browser');
  await library.locator('.opening-results').waitFor();
  assert.equal(await library.evaluate((element) => element.open), true);
  assert.equal(requests, 0, 'Exploring openings must not contact Lichess');
  const search = library.getByRole('searchbox');
  await search.fill('Légal queen lure');
  assert.equal(await library.locator('.opening-results li').count(), 1);
  await library.locator('.opening-results button').click();
  await library.getByRole('button', { name: /Add Légal queen lure.*to favourites/ }).click();
  assert.equal(await library.getByRole('button', { name: /Remove Légal queen lure.*from favourites/ }).getAttribute('aria-pressed'), 'true');
  await library.getByLabel('Favourites only', { exact: true }).check();
  await search.fill('');
  assert.equal(await library.locator('.opening-results li').count(), 1);
  const slider = library.getByRole('slider', { name: 'Preview opening move', exact: true });
  await slider.evaluate((input) => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, '4');
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
  assert.match(await library.locator('.opening-preview-navigation').innerText(), /Ply 4 \/ 15/);
  assert.equal(await library.getByRole('img', { name: 'Opening preview, White to move' }).count(), 1);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Opening library fits 320 px');
  await library.locator('.opening-statistics > summary').click();
  assert.equal(requests, 0, 'Opening statistics panel remains opt-in');
  const stats = library.locator('.opening-statistics');
  await stats.getByRole('button', { name: 'Request human statistics for preview', exact: true }).click();
  await stats.getByText(/10 rated games/).waitFor();
  assert.equal(requests, 1);
  await stats.getByRole('button', { name: 'Request human statistics for preview', exact: true }).click();
  await stats.getByText(/Cached/).waitFor();
  assert.equal(requests, 1, 'Repeated statistics request uses local cache');
  await stats.getByLabel('1800', { exact: true }).check();
  await stats.getByRole('button', { name: 'Request human statistics for preview', exact: true }).click();
  await stats.getByText(/Lichess is limiting requests/).waitFor();
  assert.equal(requests, 2);
  await stats.getByRole('button', { name: 'Request human statistics for preview', exact: true }).click();
  assert.equal(requests, 2, 'Rate limiting prevents a repeated network call');
  await page.context().setOffline(true);
  await search.fill('Légal');
  assert.equal(await library.locator('.opening-results li').count(), 1, 'Offline catalogue remains searchable');
  await page.context().setOffline(false);
  await library.getByRole('button', { name: 'Start at preview position', exact: true }).click();
  await page.getByRole('region', { name: 'Start a new game', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Opening start mode', { exact: true }).inputValue(), 'position');
  await page.getByRole('button', { name: 'Start new game', exact: true }).click();
  await page.locator('.board-wrap [data-square="f3"] [data-piece="wN"]').waitFor();
  assert.equal(await page.locator('.board-wrap [data-square="c6"] [data-piece="bN"]').count(), 1, 'Preview position is used rather than the complete trap line');
  assert.equal(await page.locator('.move-row').count(), 2, 'Four opening plies are retained in the score sheet');
  assert.equal(await page.getByRole('button', { name: 'Opening guidance', exact: true }).count(), 1);
  await page.screenshot({ path: 'artifacts/openings/mobile-preview-start.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Explore openings', exact: true }).click();
  await library.locator('.opening-results').waitFor();
  await page.screenshot({ path: 'artifacts/openings/desktop-library.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('Opening browser checks passed: offline search/favourites, opt-in statistics/cache/429, exact preview start with PGN prefix, guidance and 320 px layout.');
} finally { await browser.close(); }
