import assert from 'node:assert/strict';
import { Chess } from 'chess.js';
import { inferScreenshotTurn, placementForPreview, rotatePlacement, screenshotFen, setPlacementSquare, validatePosition } from '../src/import/position';

const start = new Chess().fen();
assert.equal(validatePosition(`  ${start.replaceAll(' ', '  ')}  `).fen, start);
assert.equal(screenshotFen(start.split(' ')[0], 'b').split(' ').slice(1).join(' '), 'b - - 0 1');
assert.equal(rotatePlacement(rotatePlacement(start.split(' ')[0])), start.split(' ')[0]);
assert.ok(validatePosition('8/8/8/8/8/8/4k3/4K3 w - - 0 1').error, 'Adjacent kings must not be loaded');
assert.ok(validatePosition('4k3/8/8/8/8/8/8/4K3 w K - 0 1').error, 'Castling needs the matching rook');
assert.ok(validatePosition('4k3/8/8/8/8/8/8/4K2R w KK - 0 1').error, 'Duplicate castling rights must not be loaded');
assert.ok(validatePosition('4k3/8/8/8/8/8/8/4K3 w - - 0garbage 1').error, 'Malformed clocks must not be loaded');
assert.ok(validatePosition('4k3/8/8/8/8/8/8/4K3 w - - 0 1').fen, 'Valid sparse positions should load');
assert.ok(validatePosition('7k/6Q1/5K2/8/8/8/8/8 b - - 0 1').fen, 'Legal checkmate positions should load');
assert.ok(validatePosition('7k/6Q1/5K2/8/8/8/8/8 w - - 0 1').error, 'The side that just moved cannot stay in check');
assert.ok(validatePosition(start.replace(' w ', ' b ')).fen, 'Side to move is independent of the board screenshot');
const misreadKing = '8/8/8/8/8/8/8/4K2R';
assert.ok(placementForPreview(misreadKing), 'A board missing a recognized king must remain visible for correction');
assert.ok(validatePosition(screenshotFen(misreadKing)).error, 'An incomplete recognition cannot load as a legal position');
const correctedKing = setPlacementSquare(misreadKing, 'e8', 'bK');
assert.ok(correctedKing && validatePosition(screenshotFen(correctedKing)).fen, 'A visual king correction must produce a loadable position');
assert.equal(placementForPreview('9/8/8/8/8/8/8/4K3'), null, 'Malformed placement cannot overrun a preview rank');
const knightCheck = 'r6q/1ppk1pQp/pNn1pn2/3p3b/1b1P1B2/3BP2N/PPP2PPP/2K4R';
assert.deepEqual(inferScreenshotTurn(start.split(' ')[0], 'black'), { turn: 'b', source: 'orientation' }, 'Black at the bottom defaults to Black to move');
assert.deepEqual(inferScreenshotTurn(start.split(' ')[0], 'white'), { turn: 'w', source: 'orientation' }, 'White at the bottom defaults to White to move');
assert.deepEqual(inferScreenshotTurn(knightCheck, 'black'), { turn: 'b', source: 'check' }, 'The user screenshot has Black in check after Nb6+');
assert.deepEqual(inferScreenshotTurn(knightCheck, 'white'), { turn: 'b', source: 'check' }, 'Check overrides the bottom-player assumption');
assert.deepEqual(inferScreenshotTurn('k3r3/8/8/8/8/8/8/4K3', 'black'), { turn: 'w', source: 'check' }, 'White in check overrides a Black-facing board');
const wrongTurn = validatePosition(screenshotFen(knightCheck, 'w'));
assert.equal(wrongTurn.suggestedTurn, 'b', 'A pasted wrong-turn FEN gets a concrete correction');
assert.match(wrongTurn.error!, /Black is in check/);
const correctedTurn = validatePosition(screenshotFen(knightCheck, 'b'));
assert.ok(correctedTurn.fen, 'The corrected user position is legal');
assert.equal(new Chess(correctedTurn.fen).move('cxb6')?.lan, 'c7b6', 'Black can capture the checking knight');
assert.deepEqual(inferScreenshotTurn(misreadKing, 'black'), { turn: 'b', source: 'orientation' }, 'Missing kings stay editable without crashing inference');
assert.equal(validatePosition('4k3/4R3/8/8/8/8/4r3/4K3 w - - 0 1').suggestedTurn, undefined, 'Both kings in check cannot be repaired by changing the turn');
console.log('Position import validation passed (26 checks).');
