import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';

const appUrl = process.env.TRAPPY_TEST_URL ?? 'http://127.0.0.1:5173';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [];
try {
  const desktop = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  desktop.on('pageerror', (error) => errors.push(error.message));
  const sparse = '4k3/8/8/8/8/8/8/4K2R w - - 0 1';
  await desktop.goto(`${appUrl}/?mode=play&fen=${encodeURIComponent(sparse)}`);
  await desktop.locator('.board-wrap [data-square="h1"] [data-piece="wR"]').waitFor();
  assert.equal(await desktop.getByRole('button', { name: 'Ruthless', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(await desktop.getByRole('button', { name: '1000', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(await desktop.getByRole('button', { name: 'Play', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(await desktop.getByLabel('Search depth', { exact: true }).isVisible(), false, 'Technical settings must be collapsed by default');
  await desktop.getByRole('button', { name: '800', exact: true }).click();
  assert.match(await desktop.locator('.board-meta').innerText(), /800 profile/);
  await desktop.getByRole('button', { name: 'Flip board', exact: true }).click();
  assert.equal(await desktop.locator('.board-wrap [data-piece]').count(), 3, 'Flip must preserve imported position');
  await desktop.getByRole('button', { name: 'New game', exact: true }).click();
  await desktop.getByLabel('New game colour').selectOption('b');
  assert.equal(await desktop.locator('.board-wrap [data-piece]').count(), 3, 'Choosing a new-game colour must preserve the board until Start is clicked');
  await desktop.getByLabel('New game colour').selectOption('w');
  await desktop.getByRole('button', { name: 'Start new game', exact: true }).click();
  await desktop.waitForFunction(() => document.querySelectorAll('.board-wrap [data-piece]').length === 32);
  assert.equal(await desktop.locator('.board-wrap [data-piece]').count(), 32);
  await desktop.getByRole('button', { name: 'Stockfish', exact: true }).click();
  await desktop.locator('.board-wrap [data-square="e2"]').click();
  assert.match(await desktop.locator('.board-wrap [data-square="e4"]').innerHTML(), /radial-gradient/, 'Clicking a piece must show legal targets');
  await desktop.locator('.board-wrap [data-square="e5"]').click();
  assert.equal(await desktop.locator('.board-wrap [data-square="e2"] [data-piece="wP"]').count(), 1, 'An illegal destination must not move a piece');
  await desktop.locator('.board-wrap [data-square="e2"]').click();
  await desktop.locator('.board-wrap [data-square="e4"]').click();
  await desktop.locator('.board-wrap [data-square="e4"] [data-piece="wP"]').waitFor();
  assert.equal(await desktop.locator('.move-row').first().locator('span').nth(1).innerText(), 'e4');

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  mobile.on('pageerror', (error) => errors.push(error.message));
  const promotionFen = '4k3/P7/8/8/8/8/8/4K3 w - - 0 1';
  const keyboard = await browser.newPage();
  keyboard.on('pageerror', (error) => errors.push(error.message));
  await keyboard.goto(`${appUrl}/?mode=play&fen=${encodeURIComponent(promotionFen)}`);
  await keyboard.getByRole('button', { name: 'a7: White pawn', exact: true }).focus();
  await keyboard.keyboard.press('Enter');
  await keyboard.keyboard.press('ArrowUp');
  assert.equal(await keyboard.locator('#trappy-board-keyboard-a8').evaluate((element) => document.activeElement === element), true, 'Arrow keys move board focus');
  await keyboard.keyboard.press('Enter');
  await keyboard.getByRole('dialog').waitFor();
  assert.equal(await keyboard.getByRole('button', { name: 'Queen', exact: true }).evaluate((element) => document.activeElement === element), true, 'Promotion chooser must focus the first choice');
  await keyboard.keyboard.press('Shift+Tab');
  assert.equal(await keyboard.getByRole('button', { name: 'Cancel promotion', exact: true }).evaluate((element) => document.activeElement === element), true, 'Promotion chooser must retain keyboard focus');
  await keyboard.keyboard.press('Escape');
  assert.equal(await keyboard.getByRole('dialog').count(), 0);
  assert.equal(await keyboard.locator('#trappy-board-keyboard-a7').evaluate((element) => document.activeElement === element), true, 'Cancel returns focus to the pawn');
  await keyboard.close();
  await mobile.goto(`${appUrl}/?mode=play&fen=${encodeURIComponent(promotionFen)}`);
  await mobile.locator('.board-wrap [data-square="a7"] [data-piece="wP"]').waitFor();
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Mobile must not scroll sideways');
  await mobile.locator('.board-wrap [data-square="a7"]').tap();
  await mobile.locator('.board-wrap [data-square="a8"]').tap();
  await mobile.getByRole('dialog', { name: 'Choose your promotion' }).waitFor();
  assert.equal(await mobile.locator('.board-wrap [data-square="a7"] [data-piece="wP"]').count(), 1, 'Promotion must wait for the player’s choice');
  await mobile.getByRole('button', { name: 'Knight', exact: true }).tap();
  await mobile.locator('.board-wrap [data-square="a8"] [data-piece="wN"]').waitFor();
  assert.match(await mobile.locator('.panel-header p').innerText(), /Drawn game/, 'Underpromotion must produce the selected piece and correct result');
  assert.equal(await mobile.getByRole('dialog').count(), 0);
  await mobile.getByRole('button', { name: 'Analyze', exact: true }).tap();
  await mobile.getByTestId('analysis-board').waitFor();
  assert.equal(await mobile.getByTestId('analysis-board').isVisible(), true, 'The workspace switch must open independent position research');
  await mobile.getByRole('button', { name: 'Play AI', exact: true }).tap();
  assert.equal(await mobile.locator('.board-wrap [data-square="a8"] [data-piece="wN"]').count(), 1, 'Returning from analysis must preserve the game and chosen promotion');
  assert.match(await mobile.locator('.panel-header p').innerText(), /Drawn game/, 'Switching workspaces must preserve the game result');
  await mobile.goto(`${appUrl}/?mode=play&fen=${encodeURIComponent(promotionFen)}`);
  await mobile.locator('.board-wrap [data-square="a7"]').tap();
  await mobile.locator('.board-wrap [data-square="a8"]').tap();
  await mobile.getByRole('dialog').waitFor();
  await mobile.keyboard.press('Escape');
  assert.equal(await mobile.getByRole('dialog').count(), 0, 'Escape must cancel promotion without moving');
  assert.equal(await mobile.locator('.board-wrap [data-square="a7"] [data-piece="wP"]').count(), 1);
  assert.deepEqual(errors, []);
  console.log('UX browser checks passed: Ruthless/1000/Play defaults, collapsed advanced settings, profile changes, safe board flip/new game, click legal targets/illegal moves, board keyboard navigation, promotion focus/choice/cancel, preserved game across workspaces, real mobile taps, and no horizontal overflow.');
} finally { await browser.close(); }
